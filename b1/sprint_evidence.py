"""Generate SPRINT-30 evidence and SPRINT30_TEST_REPORT.md from recorded runs."""
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / 'b1/evidence_sprint30'
KEYS = ('seed', 'status', 'terminal', 'score', 'end_ms', 'decisions_total', 'decisions_by_role',
        'trace_hash', 'state_hash', 'wall_s')


def cli(*args):
    r = subprocess.run([sys.executable, '-m', 'b1.match_run', *args], cwd=ROOT, text=True, capture_output=True, timeout=900)
    if r.returncode:
        return {'status': 'crashed', 'error': r.stderr[-600:]}
    return json.loads(r.stdout.strip().splitlines()[-1])


def main(extra_seeds):
    EV.mkdir(exist_ok=True)
    summary = {'generated_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
               'head': subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True, capture_output=True).stdout.strip()}
    a = cli('--seed', '1', '--out', str(EV / 'match_seed1.json'))
    b = cli('--seed', '1', '--telemetry-off')
    summary['match_seed1'] = a
    summary['replay'] = {'run1': [a.get('trace_hash'), a.get('state_hash')], 'run2': [b.get('trace_hash'), b.get('state_hash')],
                         'identical': a.get('trace_hash') is not None and a.get('trace_hash') == b.get('trace_hash')
                         and a.get('state_hash') == b.get('state_hash')}
    g1 = [cli('--scenario', 'g1', '--seed', str(s), '--telemetry-off') for s in range(1, 13)]
    cli('--scenario', 'g1', '--seed', '1', '--out', str(EV / 'g1_seed1.json'))
    summary['g1'] = [{k: r.get(k) for k in KEYS} for r in g1]
    summary['g1_close'] = [{k: r.get(k) for k in KEYS} | {'kinds': r.get('decisions_by_kind')} for r in (cli('--scenario', 'g1_close', '--seed', str(s), '--telemetry-off') for s in range(1, 13))]
    multi = []
    for s in extra_seeds:
        r = cli('--seed', str(s), '--telemetry-off')
        multi.append({k: r.get(k) for k in KEYS} | ({'error': r['error']} if 'error' in r else {}))
    summary['multi_seed'] = {'attempted': len(extra_seeds), 'completed': sum(r.get('status') == 'final' for r in multi),
                             'failed': sum(r.get('status') != 'final' for r in multi), 'runs': multi}
    tests = {}
    for mod in ('b1.test_sprint', 'b1.test_m1'):
        r = subprocess.run([sys.executable, '-W', 'ignore', '-m', 'unittest', mod, '-v'], cwd=ROOT, text=True, capture_output=True, timeout=900)
        lines = [l for l in r.stderr.splitlines() if ' ... ' in l or l.startswith(('Ran ', 'OK', 'FAILED'))]
        (EV / f'tests_{mod.split(".")[1]}.txt').write_text('\n'.join(lines) + '\n')
        tests[mod] = {'returncode': r.returncode, 'ran': next((l for l in lines if l.startswith('Ran ')), ''),
                      'verdict': lines[-1] if lines else '', 'not_ok': [l for l in lines if ' ... ' in l and not l.endswith('ok')]}
    summary['tests'] = tests
    (EV / 'summary.json').write_text(json.dumps(summary, sort_keys=True, indent=1) + '\n')
    m = summary['match_seed1']
    L = ['# SPRINT30 TEST REPORT', '', f"Generated by `python -m b1.sprint_evidence` at {summary['generated_utc']} on tree HEAD `{summary['head']}` (+ uncommitted working tree at generation time).",
         'Status vocabulary: IMPLEMENTED / TESTED only. **Nothing is ACCEPTED.**', '', '## Test suites (actually run)', '']
    for mod, t in tests.items():
        L += [f"- `{mod}`: {t['ran']} -> **{t['verdict']}**"] + [f"  - NOT OK: `{x}`" for x in t['not_ok']]
    L += ['', '## One end-to-end match (real pipeline, seed 1)', '',
          f"- status `{m.get('status')}`, result `{m.get('result')}`, simulated end `{m.get('end_ms')}` ms, wall {m.get('wall_s')} s",
          f"- decisions: total {m.get('decisions_total')}, by role {m.get('decisions_by_role')}",
          f"- decisions by kind: {m.get('decisions_by_kind')}", f"- admissions: {m.get('admissions')}",
          f"- physical outcomes: {m.get('outcomes_by_status')}", f"- decisions by athlete: {m.get('decisions_by_athlete')}",
          f"- trace hash `{m.get('trace_hash')}`", '', '## Deterministic replay (seed 1, two separate processes)', '',
          f"- run1 {summary['replay']['run1']}", f"- run2 {summary['replay']['run2']}", f"- identical: **{summary['replay']['identical']}**",
          '', '## G1 three-athlete scenario (carrier, receiver, defender all deciding), seeds 1-12', '',
          '| seed | terminal | end ms | decisions |', '|---|---|---|---|']
    L += [f"| {r['seed']} | {r['terminal']} | {r['end_ms']} | {r['decisions_total']} |" for r in summary['g1']]
    L += ['', '## G1 contested variant (defender starts on the passing lane), seeds 1-12', '', '| seed | terminal | end ms | decision kinds |', '|---|---|---|---|']
    L += [f"| {r['seed']} | {r['terminal']} | {r['end_ms']} | {r['kinds']} |" for r in summary['g1_close']]
    ms = summary['multi_seed']
    L += ['', '## Additional full-match seeds', '']
    if not ms['attempted']:
        L += ['multi-seed runs not performed']
    else:
        L += [f"attempted {ms['attempted']}, completed {ms['completed']}, failed {ms['failed']}", '', '| seed | status | score | decisions | trace hash |', '|---|---|---|---|---|']
        L += [f"| {r.get('seed')} | {r.get('status')} | {r.get('score')} | {r.get('decisions_total')} | `{str(r.get('trace_hash'))[:16]}` |" for r in ms['runs']]
    L += ['', '## Not run', '', '- No 4 x 600 s league-profile match; no RULES_V03 profile; no performance budget test; no statistical calibration against B0.',
          '- Independent review: see `b1/evidence_sprint30/INDEPENDENT_REVIEW.md` (written by a separate agent).', '',
          '## Reproduce', '', '```', 'pip install scipy numpy', 'python -m unittest b1.test_sprint -v', 'python -m unittest b1.test_m1',
          'python -m b1.match_run --seed 1 --out /tmp/match.json', 'python -m b1.match_run --scenario g1 --seed 1', 'python -m b1.sprint_evidence 2 3 4', '```', '']
    (ROOT / 'SPRINT30_TEST_REPORT.md').write_text('\n'.join(L))
    print(json.dumps({k: summary[k] for k in ('replay', 'tests')}, sort_keys=True)[:1500])
    print(json.dumps(summary['multi_seed'])[:1200])


if __name__ == '__main__':
    main([int(x) for x in sys.argv[1:]])
