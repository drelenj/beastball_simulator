"""Generate SPRINT-45 evidence and SPRINT45_TEST_REPORT.md from recorded runs."""
import json
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / 'b1/evidence_sprint45'
KEYS = ('seed', 'status', 'terminal', 'result', 'score', 'end_ms', 'decisions_total', 'decisions_by_role',
        'outcomes_by_status', 'trace_hash', 'state_hash', 'wall_s')


def cli(*args):
    r = subprocess.run([sys.executable, '-m', 'b1.match_run', *args], cwd=ROOT, text=True, capture_output=True, timeout=900)
    if r.returncode:
        return {'status': 'crashed', 'error': r.stderr[-600:]}
    return json.loads(r.stdout.strip().splitlines()[-1])


def main(extra_seeds):
    EV.mkdir(exist_ok=True)
    S = {'generated_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
         'head': subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True, capture_output=True).stdout.strip(),
         'dirty': bool(subprocess.run(['git', 'status', '--porcelain', '--', 'b1/*.py'], cwd=ROOT, text=True, capture_output=True).stdout.strip())}
    a = cli('--seed', '1', '--out', str(EV / 'match_seed1.json'))
    b = cli('--seed', '1', '--telemetry-off')
    S['match_seed1'] = a
    S['replay'] = {'run1': [a.get('trace_hash'), a.get('state_hash')], 'run2': [b.get('trace_hash'), b.get('state_hash')],
                   'identical': a.get('trace_hash') is not None and (a.get('trace_hash'), a.get('state_hash')) == (b.get('trace_hash'), b.get('state_hash'))}
    S['g1'] = [{k: r.get(k) for k in KEYS} for r in (cli('--scenario', 'g1', '--seed', str(s), '--telemetry-off') for s in range(1, 13))]
    S['g1_close'] = [{k: r.get(k) for k in KEYS} for r in (cli('--scenario', 'g1_close', '--seed', str(s), '--telemetry-off') for s in range(1, 13))]
    cli('--scenario', 'g1', '--seed', '1', '--out', str(EV / 'g1_seed1.json'))
    S['p1_sensitivity'] = []
    for p1 in (250, 500, 1000):
        r = cli('--seed', '1', '--max-ms', '60000', '--telemetry-off', '--p1-ms', str(p1))
        S['p1_sensitivity'].append({'p1_ms': p1, 'score': r.get('score'), 'decisions_total': r.get('decisions_total'),
                                    'ledger_by_event': (r.get('rules') or {}).get('ledger_by_event'), 'trace_hash': r.get('trace_hash')})
    multi = []
    for s in extra_seeds:
        r = cli('--seed', str(s), '--telemetry-off')
        multi.append({k: r.get(k) for k in KEYS} | ({'error': r['error']} if 'error' in r else {}))
    S['multi_seed'] = {'attempted': len(extra_seeds), 'completed': sum(r.get('status') == 'final' for r in multi),
                       'failed': sum(r.get('status') != 'final' for r in multi), 'runs': multi}
    r = subprocess.run([sys.executable, '-m', 'pytest', '-q', '-rA', 'b1', '-p', 'no:cacheprovider', '-W', 'ignore'], cwd=ROOT, text=True, capture_output=True, timeout=900)
    lines = [l for l in r.stdout.splitlines() if l.startswith(('PASSED', 'FAILED', 'ERROR')) or ' passed' in l or ' failed' in l]
    (EV / 'tests_pytest_b1.txt').write_text('\n'.join(lines) + '\n')
    S['tests'] = {'command': 'python3 -m pytest -q b1', 'returncode': r.returncode, 'summary': lines[-1] if lines else '',
                  'passed': sum(l.startswith('PASSED') for l in lines), 'not_ok': [l for l in lines if l.startswith(('FAILED', 'ERROR'))],
                  'by_file': dict(Counter(l.split('::')[0].split()[-1] for l in lines if l.startswith('PASSED')))}
    (EV / 'summary.json').write_text(json.dumps(S, sort_keys=True, indent=1) + '\n')
    m, ms, t = S['match_seed1'], S['multi_seed'], S['tests']
    term = lambda rows: dict(Counter(str(x['terminal']) for x in rows))
    L = ['# SPRINT45 TEST REPORT', '', f"Generated by `python -m b1.sprint45_evidence` at {S['generated_utc']} on HEAD `{S['head']}`" + (' (+ uncommitted b1 changes)' if S['dirty'] else '') + '.',
         'Status words: IMPLEMENTED / TESTED only. **Nothing is ACCEPTED.** Numbers below are single runs unless stated; no effect claim is made from any outcome count.', '',
         '## Test suites (actually run)', '', f"- `{t['command']}` -> **{t['summary']}**; passed per file: {t['by_file']}"] + [f"  - NOT OK: `{x}`" for x in t['not_ok']]
    L += ['', '## One end-to-end match (real pipeline, seed 1, ruleset 1.0.2, P-1 = 500 ms)', '',
          f"- status `{m.get('status')}`, result `{m.get('result')}`, simulated end {m.get('end_ms')} ms, wall {m.get('wall_s')} s",
          f"- decisions: total {m.get('decisions_total')}, by role {m.get('decisions_by_role')}", f"- decisions by kind: {m.get('decisions_by_kind')}",
          f"- decisions by athlete: {m.get('decisions_by_athlete')}", f"- admissions: {m.get('admissions')}",
          f"- physical outcomes (from recorded events; `unknown:*` are unattributed): {m.get('outcomes_by_status')}",
          f"- rules-state ledger: {(m.get('rules') or {}).get('ledger_entries')} entries; by row {(m.get('rules') or {}).get('ledger_by_row')}; by event {(m.get('rules') or {}).get('ledger_by_event')}; Keeper contacts checked {(m.get('rules') or {}).get('keeper_contacts_checked')}",
          f"- pass-release-v1: {m.get('release_contract')}; receiver checks at release {m.get('own5_pass_releases_checked')}",
          f"- trace hash `{m.get('trace_hash')}`", '', '## Deterministic replay (seed 1, two separate processes)', '',
          f"- run1 {S['replay']['run1']}", f"- run2 {S['replay']['run2']}", f"- identical: **{S['replay']['identical']}**", '',
          '## G1 three-athlete scenarios, seeds 1-12 each (terminal from recorded events)', '', f"- open lane: {term(S['g1'])}", f"- defender on lane: {term(S['g1_close'])}",
          '- 12 seeds per condition is too few for any rate claim; none is made.', '',
          '## P-1 threshold runs in the engine (seed 1, first 60 s; descriptive only)', '', '| P-1 ms | score | decisions | ledger events |', '|---|---|---|---|']
    L += [f"| {x['p1_ms']} | {x['score']} | {x['decisions_total']} | {x['ledger_by_event']} |" for x in S['p1_sensitivity']]
    L += ['', 'One seed per threshold: differences between rows are NOT evidence of a gameplay effect (any perturbation changes a trajectory). The unit tests show the threshold mechanism itself (flip exactly at the threshold).', '', '## Additional full-match seeds', '']
    if not ms['attempted']:
        L += ['multi-seed runs not performed']
    else:
        L += [f"attempted {ms['attempted']}, completed {ms['completed']}, failed {ms['failed']}", '', '| seed | status | result | decisions | trace hash |', '|---|---|---|---|---|']
        L += [f"| {x.get('seed')} | {x.get('status')} | {x.get('result')} | {x.get('decisions_total')} | `{str(x.get('trace_hash'))[:16]}` |" for x in ms['runs']]
    L += ['', '## Not run', '', '- 4 x 600 s league profile; 100-seed matrices; paired sign tests for any policy or rating effect; behavioural gates; performance budget; B0-vs-B1 comparison; the Base A governed G1 matrix was not regenerated (its 25 tests were run).',
          '- Independent review: `b1/evidence_sprint45/INDEPENDENT_REVIEW.md` (separate agent; describes the code at the time it ran).', '',
          '## Reproduce', '', '```', 'pip install scipy numpy pytest', 'python3 -m pytest -q b1', 'python -m b1.match_run --seed 1 --out /tmp/match.json',
          'python -m b1.match_run --scenario g1 --seed 1', 'python -m b1.sprint45_evidence 2 3 4 && python -m b1.sprint45_reports', '```', '']
    (ROOT / 'SPRINT45_TEST_REPORT.md').write_text('\n'.join(L))
    print(json.dumps({'replay': S['replay']['identical'], 'tests': t['summary'], 'not_ok': t['not_ok'], 'seed1': m.get('result'),
                      'multi': [(x.get('seed'), x.get('status'), x.get('score')) for x in multi]}))


if __name__ == '__main__':
    main([int(x) for x in sys.argv[1:]])
